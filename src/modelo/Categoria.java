package modelo;

/**
 * Representa las categorías disponibles para clasificar
 * los productos registrados en el sistema de inventario.
 *
 * @author anmunozc
 */
public enum Categoria {

    /**
     * Representa los productos correspondientes a computadores.
     */
    COMPUTADOR,

    /**
     * Representa los productos correspondientes a teléfonos.
     */
    TELEFONO,

    /**
     * Representa los productos correspondientes a accesorios.
     */
    ACCESORIO

}